"""Regenerate src/preset_files.rs from factory/<Category>/*.preset (category order below)."""
import os
ORDER = ["Stage", "Twin", "Leslie", "Studio", "Worn"]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
cats = [c for c in ORDER if os.path.isdir(os.path.join(root, "factory", c))]
cats += sorted(c for c in os.listdir(os.path.join(root, "factory")) if c not in cats and os.path.isdir(os.path.join(root, "factory", c)))
lines = ["// Generated by tools/gen_presets.py — do not edit.", "const FILES: &[&str] = &["]
for c in cats:
    for f in sorted(os.listdir(os.path.join(root, "factory", c)), key=lambda n: (n != "Factory.preset", n)):
        if f.endswith(".preset"):
            lines.append(f'    include_str!("../factory/{c}/{f}"),')
lines.append("];")
open(os.path.join(root, "src", "preset_files.rs"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
