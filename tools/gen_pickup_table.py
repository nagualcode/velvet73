"""Generate src/dsp/pickup_table.rs: axial field Bz of the standard Rhodes pole piece
(US 4,040,321 Fig. 8 geometry; surface magnetic charges, see analysis/field.py and docs/PICKUP_ANALYSIS.md)
on a grid of radial tine-tip distance rho (mm) x tip-to-pole gap (mm). The pole is axisymmetric, so the
flux seen by the coil depends on the tip's radial distance from the pole axis only (both polarizations)."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "analysis"))
import numpy as np
from field import pole_charges, B
IN = 25.4
P, Q = pole_charges(shape="cone", n=60)
RHO_N, RHO_STEP = 301, 0.05      # 0..15 mm
GAP_N, GAP0, GAP_STEP = 19, 0.4, 0.2   # 0.4..4.0 mm
rho = np.arange(RHO_N) * RHO_STEP
tab = np.zeros((GAP_N, RHO_N))
for gi in range(GAP_N):
    g = GAP0 + gi * GAP_STEP
    pts = np.stack([np.zeros(RHO_N), rho / IN, np.full(RHO_N, g / IN)], 1)
    tab[gi] = np.concatenate([B(pts[i:i+50], P, Q)[:, 2] for i in range(0, RHO_N, 50)])
tab /= tab[int(round((1.6 - GAP0) / GAP_STEP)), 0]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "dsp", "pickup_table.rs")
with open(out, "w") as f:
    f.write("//! Generated by tools/gen_pickup_table.py — do not edit.\n")
    f.write("//! Axial field of the Rhodes pole piece vs tip radial distance (rows: gap).\n")
    f.write(f"pub const RHO_N: usize = {RHO_N};\npub const RHO_STEP_MM: f32 = {RHO_STEP};\n")
    f.write(f"pub const GAP_N: usize = {GAP_N};\npub const GAP0_MM: f32 = {GAP0};\npub const GAP_STEP_MM: f32 = {GAP_STEP};\n")
    f.write(f"pub static FIELD: [[f32; RHO_N]; GAP_N] = [\n")
    for row in tab:
        f.write("    [" + ", ".join(f"{v:.6e}" for v in row) + "],\n")
    f.write("];\n")
print("wrote", out, tab.shape, "range", tab.min(), tab.max())
